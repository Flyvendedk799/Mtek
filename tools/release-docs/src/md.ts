// Small Markdown helpers shared by the renderers.

/** A table cell: no pipes, no line breaks. */
export function cell(text: string): string {
  return text.replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim();
}

export function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const lines = [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`];
  for (const row of rows) lines.push(`| ${row.map(cell).join(" | ")} |`);
  return lines.join("\n");
}

export function code(text: string): string {
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}

/** A link from a file in `docs/` to a repository path. */
export function repoLink(path: string, label = path): string {
  return `[${label}](../${path})`;
}

export const GENERATED_NOTE = (generator: string): string =>
  `<!-- Generated by tools/release-docs (${generator}). Do not edit by hand: change the sources it reads, then run \`npm run generate -w @mtek/release-docs\`. -->`;

/** Demote the headings of `markdown` by `by` levels, leaving fenced code alone. */
export function demoteHeadings(markdown: string, by: number): string {
  let fenced = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (/^```/.test(line)) fenced = !fenced;
      if (fenced) return line;
      const m = /^(#+) (.*)$/.exec(line);
      return m === null ? line : `${"#".repeat((m[1]?.length ?? 1) + by)} ${m[2] ?? ""}`;
    })
    .join("\n");
}

/** Where a decision number points from `docs/`. */
export function decisionLink(number: string, files: readonly string[]): string {
  const file = files.find((f) => f.startsWith(`${number}-`));
  return file === undefined ? number : `[${number}](../spec/decisions/${file})`;
}
