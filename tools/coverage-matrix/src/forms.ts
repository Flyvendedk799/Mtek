// The forms of the language reference that the registry has no row for (decision 0093).
//
// `mtek context` lists the constructs (`functions`, `materials`, `bind`, `arithmetic`, ...) and every
// row of the standard-library registry (`function:sin`, `schema:Box`, `event:key_down`, ...) as
// `supported.features`. The language reference (`spec/language.md`, `spec/scenes.md`,
// `spec/physics.md`, `spec/materials.md`, `spec/runtime-abi.md`) says more: which statements exist,
// which operators, which places can be assigned, what a binding may read, which host input codecs
// there are. Those are the forms below. A form is a node, a discriminator or a number the compiler
// writes into its typed IR or manifest; `facts.ts` derives them from there.
//
// `IR_VARIANTS` is the drift guard: every variant of the IR enums that the facts read is accounted
// for here (by the form or the registry id it feeds), and a unit test compares the table with
// `crates/mtek-compiler/src/ir/model.rs`, so a new IR node fails the tool until it is a form.

export interface Form {
  id: string;
  group: string;
  title: string;
  /** Where the language reference describes it. */
  ref: string;
}

function forms(group: string, ref: string, entries: readonly (readonly [string, string])[]): Form[] {
  return entries.map(([id, title]) => ({ id, group, title, ref }));
}

