// `docs/coverage-matrix.md`, printed from the model of `matrix.ts`. Deterministic: no dates, no machine
// paths, no compiler build ids; the same programs and the same compiler give the same bytes.
import { DEMONSTRATIONS, OTHER_EXAMPLES } from "./projects.ts";
import type { FeatureRow, Matrix } from "./matrix.ts";

const SHORT: Readonly<Record<string, string>> = {
  "examples/material-configurator": "CFG",
  "examples/physics-playground": "PHY",
  "examples/modular-scene": "MOD",
};

const REGISTRY_GROUPS = [
  "construct",
  "type",
  "schema",
  "scene-object",
  "event",
  "enum",
  "namespace",
  "function",
  "value",
  "method",
  "body-command",
  "body-property",
];

const GROUP_TITLES: Readonly<Record<string, string>> = {
  construct: "Constructs",
  type: "Types",
  schema: "Schemas (descriptors)",
  "scene-object": "Scene objects",
  event: "Events",
  enum: "Enums",
  namespace: "Namespaces",
  function: "Functions",
  value: "Values",
  method: "Methods",
  "body-command": "Body commands",
  "body-property": "Body properties",
};

const cell = (text: string): string => text.replace(/\|/g, "\\|");

function mark(flag: boolean): string {
  return flag ? "x" : "";
}

function fixtureCell(row: FeatureRow): string {
  const first = row.fixtures[0];
  if (first === undefined) return "";
  const more = row.fixtures.length > 1 ? ` (+${row.fixtures.length - 1})` : "";
  return `\`${first}\`${more}`;
}

function featureTable(rows: readonly FeatureRow[], withTitle: boolean): string[] {
  const head = ["Feature", ...(withTitle ? ["Form"] : ["Neg"]), ...DEMONSTRATIONS.map((id) => SHORT[id] ?? id), "PUL", "Positive fixture"];
  const lines = [`| ${head.join(" | ")} |`, `|${head.map((_, i) => (i === 0 || (withTitle && i === 1) || i === head.length - 1 ? "---" : ":-:")).join("|")}|`];
  for (const row of rows) {
    const id = `\`${cell(row.id)}\`${row.resolverOnly ? " †" : ""}`;
    lines.push(
      `| ${[id, withTitle ? cell(row.title) : row.named === null ? "" : String(row.named), ...row.demos.map(mark), mark(row.example), fixtureCell(row)].join(" | ")} |`,
    );
  }
  return lines;
}

export function render(matrix: Matrix): string {
  const out: string[] = [];
  const w = (...lines: string[]): void => {
    out.push(...lines);
  };
  const registry = matrix.features.filter((feature) => feature.layer === "registry");
  const forms = matrix.features.filter((feature) => feature.layer === "form");
  const demoCovered = (f: FeatureRow): boolean => f.demos.some(Boolean);
  const fixtureOnly = matrix.features.filter((f) => !demoCovered(f) && !f.example && f.fixtures.length > 0).length;
  const exampleOnly = matrix.features.filter((f) => !demoCovered(f) && f.example).length;
  const uncovered = matrix.features.filter((f) => !demoCovered(f) && !f.example && f.fixtures.length === 0);

  w(
    "# Feature coverage matrix",
    "",
    "<!-- Generated by tools/coverage-matrix (`npm run generate -w @mtek/coverage-matrix`). Do not edit by hand. -->",
    "",
    "- Status: generated; a unit test of `tools/coverage-matrix` fails when this file is stale (decision 0093).",
    `- Language version: ${matrix.languageVersion}.`,
    "- Task M7-02. Records 0002 and 0004 say what the matrix must show: each release demonstration exercises a feature no other does, every v0.1 feature is exercised by a demonstration or a named fixture, and every diagnostic code has a negative test.",
    "",
    "## 1. How the matrix is made",
    "",
    "Nothing here is read from prose. The programs (the examples and every positive fixture under `tests/`) are compiled by the real `mtek`, and what each uses is read off what the compiler produced:",
    "",
    "- the typed IR (`mtek inspect --ir --format json`): statements, expression forms, places, behaviours, bindings, entities, descriptors, cross-file references;",
    "- the program manifest (`mtek build`): host inputs and their codecs, the physics subsystem, packaged assets, lights, generated shaders;",
    "- the names the resolver and the type checker recorded for the source (`mtek_compiler::context::used_features`, through the helper `coverage-uses`): the standard-library item every name denotes, the glb accessors and body commands. The IR holds folded values, so a call that folds to a constant (`quat.identity()`, `CHAIR.node_position(\"Seat\")`) leaves nothing in it; only the resolver shows it. Features that no program shows in the IR or the manifest are marked †.",
    "",
    "The list of features is the compiler's own: `supported.features` of `mtek context` (the resolver's construct table and every row of the standard-library registry, `spec/stdlib-schema.json`), plus the forms of the language reference that have no registry row (`tools/coverage-matrix/src/forms.ts`: statements, operators, places, behaviours, bindings, entity facets, cross-file references, host input codecs).",
    "",
    "Columns: " +
      DEMONSTRATIONS.map((id) => `**${SHORT[id] ?? id}** \`${id}\``).join(", ") +
      `; **PUL** ${OTHER_EXAMPLES.map((id) => `\`${id}\``).join(", ")}, the program of M0 to M3, which is not a release demonstration (decision 0002) but is a named positive program; **Neg** the number of negative fixtures whose expected messages quote the feature by name (registry features that have a name; the codes of section 7 guard the rest); **Positive fixture** the most focused positive fixture that uses the feature (the one that uses the fewest features altogether; the roots searched are listed in \`tools/coverage-matrix/src/projects.ts\`), and how many more there are.`,
    "",
    "## 2. Result",
    "",
    "| Assertion | Result |",
    "|---|---|",
    `| Each demonstration exercises a feature no other demonstration does | ${matrix.distinct.every((d) => d.unique.length > 0) ? "holds" : "FAILS"} (${matrix.distinct.map((d) => `${SHORT[d.demonstration] ?? d.demonstration} ${d.unique.length}`).join(", ")}) |`,
    `| Each demonstration exercises its pressure of decision 0002, and no other demonstration does | ${matrix.distinct.every((d) => d.pressures.every((p) => p.own && p.others.length === 0)) ? "holds" : "FAILS"} |`,
    `| Every v0.1 feature is exercised by a demonstration or a named positive program | ${uncovered.length === 0 ? "holds" : "FAILS"} (${matrix.features.length} features: ${matrix.features.filter(demoCovered).length} by a demonstration, ${exampleOnly} by the M3 example only, ${fixtureOnly} by a fixture only) |`,
    `| Every feature belongs to a negative-test area whose codes are all tested | ${matrix.areas.every((a) => a.codes.every((c) => c.evidence !== "none" && c.evidence !== "unknown code")) && matrix.features.every((f) => f.areas.length > 0) ? "holds" : "FAILS"} (${matrix.areas.length} areas) |`,
    `| Every nearest unsupported neighbour is rejected by a fixture or a registry reservation | ${matrix.notSupported.every((n) => n.evidence !== "none") ? "holds" : "FAILS"} (${matrix.notSupported.length} entries) |`,
    `| Diagnostic codes without a fail fixture, a named negative test or a registry mark | ${matrix.codes.uncovered.length === 0 ? "none" : matrix.codes.uncovered.join(", ")} |`,
    "",
    `${matrix.positive} positive fixture programs were read; ${matrix.excluded.length} directories under the fixture roots do not check and are not positive (section 9).`,
    "",
    "## 3. The demonstrations",
    "",
  );

  for (const row of matrix.distinct) {
    w(`### \`${row.demonstration}\``, "", "Pressure (decision 0002), exercised by this demonstration alone:", "");
    w("| Fact | Exercised here | Also exercised by |", "|---|:-:|---|");
    for (const p of row.pressures) w(`| \`${p.id}\` | ${mark(p.own)} | ${p.others.length === 0 ? "-" : p.others.map((o) => `\`${o}\``).join(", ")} |`);
    w("", `Every fact that only this demonstration exercises (${row.unique.length}):`, "", row.unique.map((fact) => `\`${fact}\``).join(", "), "");
  }

  w(`## 4. Features of the registry (${registry.length})`, "", "`supported.features` of `mtek context`, by kind.", "");
  for (const group of REGISTRY_GROUPS) {
    const rows = registry.filter((f) => f.group === group).sort((a, b) => a.id.localeCompare(b.id, "en"));
    if (rows.length === 0) continue;
    w(`### ${GROUP_TITLES[group] ?? group} (${rows.length})`, "", ...featureTable(rows, false), "");
  }
  const otherGroups = [...new Set(registry.map((f) => f.group))].filter((g) => !REGISTRY_GROUPS.includes(g)).sort();
  for (const group of otherGroups) {
    const rows = registry.filter((f) => f.group === group);
    w(`### ${group} (${rows.length})`, "", ...featureTable(rows, false), "");
  }

  w(`## 5. Forms of the language reference (${forms.length})`, "");
  const formGroups = [...new Set(forms.map((f) => f.group))];
  for (const group of formGroups) {
    const rows = forms.filter((f) => f.group === group);
    const ref = rows[0]?.ref ?? "";
    w(`### ${group[0]?.toUpperCase() ?? ""}${group.slice(1)} (${rows.length})`, "", `Reference: ${ref}.`, "", ...featureTable(rows, true), "");
  }

  w(
    "## 6. Nearest unsupported neighbours",
    "",
    "`supported.notSupported` of `mtek context`: what this version of the language will not accept (decision 0004, rule 1: no silent approximation). Each has a fixture that asserts the rejection, or a registry reservation when no program can reach it.",
    "",
    "| Not supported | Code | Fixture or reservation |",
    "|---|---|---|",
  );
  for (const row of matrix.notSupported) {
    const evidence = row.evidence === "none" ? "NONE" : row.evidence.startsWith("reserved:") ? cell(row.evidence) : `\`${cell(row.evidence)}\``;
    w(`| ${cell(row.entry)} | ${row.code} | ${evidence} |`);
  }
  w("");

  w(
    "## 7. Negative tests by area",
    "",
    "A feature has no diagnostic of its own that a tool could derive, so the features are grouped into areas (`tools/coverage-matrix/src/guards.ts`) and each area names the codes that guard it. The grouping is reviewed data; the tool checks that every feature belongs to an area, that every code exists and that every code has a fixture or a named test. The evidence is the first fixture (or test file) for the code.",
    "",
    "| Area | Features | Code | Negative test |",
    "|---|--:|---|---|",
  );
  for (const row of matrix.areas) {
    row.codes.forEach((code, i) => {
      w(`| ${i === 0 ? cell(row.area.title) : ""} | ${i === 0 ? String(row.features) : ""} | ${code.code} | ${code.evidence === "none" || code.evidence === "unknown code" ? "NONE" : code.evidence.startsWith("reserved:") ? cell(code.evidence) : `\`${cell(code.evidence)}\``} |`);
    });
  }
  w("");

  const coverage = matrix.codes.coverage;
  const kinds = { fixture: 0, reserved: 0, unreachable: 0, "covered-elsewhere": 0, uncovered: 0 };
  for (const c of coverage.values()) kinds[c.kind] += 1;
  w(
    "## 8. Diagnostic codes",
    "",
    `The catalogue of \`spec/diagnostics.md\` section 5 has ${matrix.codes.catalogue.length} codes. A code has a fixture when the expected diagnostics of some fixture contain it (for a warning, a passing program that lists it). \`tests/semantics/code-coverage-exceptions.json\` lists, with a reason, the codes that no fixture can produce; the compiler's own test (\`every_catalogue_code_has_a_fixture_or_a_listed_reason\`) and this tool read the same file.`,
    "",
    "| Negative test | Codes |",
    "|---|--:|",
    `| A fixture | ${kinds.fixture} |`,
    `| A named test, because a fixture cannot express the code (generated sizes, files the source manager rejects, runtime codes) | ${kinds["covered-elsewhere"]} |`,
    `| A named test, because only a compiler defect produces the code | ${kinds.unreachable} |`,
    `| Reserved or not implemented, marked in the catalogue | ${kinds.reserved} |`,
    `| **None** | ${kinds.uncovered} |`,
    "",
    "### 8.1 Codes without a fail fixture, a named negative test or a catalogue mark",
    "",
    matrix.codes.uncovered.length === 0 ? "None." : matrix.codes.uncovered.map((c) => `- ${c}`).join("\n"),
    "",
    "### 8.2 Reserved or not implemented (marked in the catalogue)",
    "",
    "| Code | Title | Reason |",
    "|---|---|---|",
  );
  for (const entry of matrix.codes.catalogue) {
    const c = coverage.get(entry.code);
    if (c?.kind === "reserved") w(`| ${entry.code} | ${cell(entry.title)} | ${cell(c.reason)} |`);
  }
  w("", "### 8.3 Covered by a named test, not by a compiler fixture", "", "| Code | Title | Test | Reason |", "|---|---|---|---|");
  for (const entry of matrix.codes.catalogue) {
    const c = coverage.get(entry.code);
    if (c?.kind === "covered-elsewhere" || c?.kind === "unreachable") {
      w(`| ${entry.code} | ${cell(entry.title)} | \`${cell(c.test ?? "")}\` | ${c.kind === "unreachable" ? "Only a compiler defect produces it. " : ""}${cell(c.reason)} |`);
    }
  }
  w("");

  w("## 9. Programs read", "", `Positive fixture programs: ${matrix.positive}. The roots are listed in \`tools/coverage-matrix/src/projects.ts\`. Directories under them that do not check (a variant that must fail on purpose) are not positive fixtures and name no feature:`, "");
  if (matrix.excluded.length === 0) w("None.");
  for (const e of matrix.excluded) w(`- \`${e.id}\`: ${e.note.replace(/\\/g, "/")}`);
  w("");
  return out.join("\n");
}
