const BOX: readonly number[] = [0x7f, 0x41, 0x41, 0x41, 0x7f];

/** The five columns of `char`. */
export function glyphColumns(char: string): readonly number[] {
  const code = char.codePointAt(0) ?? 0;
  if (code < 32 || code > 126) return BOX;
  return GLYPHS.slice((code - 32) * 5, (code - 32) * 5 + 5);
}

/** Glyph cell: 5 pixels and 1 pixel of spacing, 8 rows. */
export const CELL_WIDTH = 6;
export const CELL_HEIGHT = 8;

/**
 * `content` as an SVG (one path of unit squares, crisp edges) in `fill`, and its size in cells. Width is
 * `6n - 1` pixels for `n` characters (no trailing spacing), at least 1.
 */
export function pixelTextSvg(content: string, fill: string): { svg: string; width: number; height: number } {
  const chars = [...content];
  let path = "";
  chars.forEach((char, index) => {
    const columns = glyphColumns(char);
    for (let x = 0; x < 5; x++) {
      const column = columns[x] ?? 0;
      for (let y = 0; y < CELL_HEIGHT; y++) {
        if ((column >> y) & 1) path += `M${String(index * CELL_WIDTH + x)} ${String(y)}h1v1h-1z`;
      }
    }
  });
  const width = Math.max(1, chars.length * CELL_WIDTH - 1);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(width)} ${String(CELL_HEIGHT)}" shape-rendering="crispEdges">` +
    `<path fill="${fill}" d="${path}"/></svg>`;
  return { svg, width, height: CELL_HEIGHT };
}

/** A CSS `url(...)` of `svg`. */
export function svgUrl(svg: string): string {
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}
