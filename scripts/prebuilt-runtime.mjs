#!/usr/bin/env node
// The prebuilt runtime checked into crates/mtek-cli/prebuilt/ (decision 0131).
//
// `mtek-cli/build.rs` embeds packages/runtime-web/dist/ and packages/physics-rapier/dist/ when they
// exist and this prebuilt copy otherwise, so that `cargo build` on a fresh clone gives an `mtek`
// that can `build` without Node. PROVENANCE.json records the sha256 of every prebuilt file and one
// hash of the sources the bundles are built from.
//
//   node scripts/prebuilt-runtime.mjs --write   copy the freshly built dist/ files (run `npm run build` first)
//   node scripts/prebuilt-runtime.mjs --check   fail when the sources changed since the last --write, or
//                                               when a prebuilt file does not match its recorded hash
//   node scripts/prebuilt-runtime.mjs --check --against-dist
//                                               also require the prebuilt files to equal dist/ byte for byte
//
// The source hash covers every tracked or untracked-but-not-ignored file under the inputs below,
// except tests; it uses only Node built-ins and `git ls-files`.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const prebuilt = join(root, "crates/mtek-cli/prebuilt");
const FILES = [
  { name: "runtime.js", from: "packages/runtime-web/dist" },
  { name: "runtime.dev.js", from: "packages/runtime-web/dist" },
  { name: "runtime.d.ts", from: "packages/runtime-web/dist" },
  { name: "physics.js", from: "packages/physics-rapier/dist" },
];
/** What the bundles are built from. */
const INPUTS = [
  "packages/runtime-web",
  "packages/physics-rapier",
  "spec/manifest.schema.json",
  "scripts/gen-manifest-validator.mjs",
  "package-lock.json",
];

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

function sourceFiles() {
  const listed = execFileSync("git", ["ls-files", "-co", "--exclude-standard", "--", ...INPUTS], { cwd: root, encoding: "utf8" });
  return listed
    .split("\n")
    .filter((path) => path !== "")
    .filter((path) => !/\.test\.ts$/.test(path) && !/(^|\/)(test|tests|dist|node_modules)\//.test(path))
    .filter((path) => existsSync(join(root, path)))
    .sort();
}

function sourceHash() {
  const hash = createHash("sha256");
  for (const path of sourceFiles()) {
    // Line endings are normalised, so a Windows checkout with autocrlf agrees.
    const text = readFileSync(join(root, path)).toString("binary").replace(/\r\n/g, "\n");
    hash.update(path).update("\0").update(text, "binary").update("\0");
  }
  return hash.digest("hex");
}

const args = new Set(process.argv.slice(2));
const provenancePath = join(prebuilt, "PROVENANCE.json");

if (args.has("--write")) {
  mkdirSync(prebuilt, { recursive: true });
  const files = {};
  for (const { name, from } of FILES) {
    const source = join(root, from, name);
    if (!existsSync(source)) {
      console.error(`prebuilt-runtime: ${from}/${name} is missing; run \`npm run build\` first`);
      process.exit(1);
    }
    copyFileSync(source, join(prebuilt, name));
    files[name] = { from: `${from}/${name}`, bytes: readFileSync(source).length, sha256: sha256(readFileSync(source)) };
  }
  const provenance = { note: "Generated by scripts/prebuilt-runtime.mjs --write; never edit by hand (decision 0131).", sources: sourceHash(), inputs: INPUTS, files };
  writeFileSync(provenancePath, JSON.stringify(provenance, null, 2) + "\n");
  console.log(`prebuilt-runtime: wrote ${FILES.length} files to crates/mtek-cli/prebuilt`);
} else if (args.has("--check")) {
  const problems = [];
  if (!existsSync(provenancePath)) problems.push("crates/mtek-cli/prebuilt/PROVENANCE.json is missing");
  else {
    const provenance = JSON.parse(readFileSync(provenancePath, "utf8"));
    for (const { name, from } of FILES) {
      const path = join(prebuilt, name);
      const recorded = provenance.files?.[name];
      if (!existsSync(path)) problems.push(`prebuilt/${name} is missing`);
      else if (recorded?.sha256 !== sha256(readFileSync(path))) problems.push(`prebuilt/${name} does not match PROVENANCE.json`);
      if (args.has("--against-dist")) {
        const built = join(root, from, name);
        if (!existsSync(built)) problems.push(`${from}/${name} is missing (run \`npm run build\`)`);
        else if (existsSync(path) && sha256(readFileSync(built)) !== sha256(readFileSync(path))) problems.push(`prebuilt/${name} differs from ${from}/${name}`);
      }
    }
    if (provenance.sources !== sourceHash()) problems.push("the runtime or physics sources changed since the prebuilt runtime was written");
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(`prebuilt-runtime: ${problem}`);
    console.error("prebuilt-runtime: refresh it with `npm run build && node scripts/prebuilt-runtime.mjs --write` and commit crates/mtek-cli/prebuilt/");
    process.exit(1);
  }
  console.log("prebuilt-runtime: the prebuilt runtime matches its sources");
} else {
  console.error("usage: node scripts/prebuilt-runtime.mjs --write | --check [--against-dist]");
  process.exit(2);
}
