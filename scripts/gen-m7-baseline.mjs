// The M7 baseline (decision 0126): one machine-readable file, `evidence/M7/baseline.json`, and the number tables of
// `evidence/M7/report.md`, both generated from stored results, so that a later change can be compared with them by a
// script and neither can drift from the data.
//
//   node scripts/gen-m7-baseline.mjs           write both
//   node scripts/gen-m7-baseline.mjs --check   fail unless the committed files are what this prints
//
// Inputs (all committed): benchmarks/results/runtime/summary*.json and report-after-quiet.md (the run record table),
// benchmarks/runtime/FROZEN.json, evidence/M7/ai-baseline.json (generated by tools/ai-eval compare-cli),
// evidence/M7/gate/{suite-summary.txt,reproducible-builds-final.json}, benchmarks/holdout.sha256.
// Nothing here is measured: it only reads, selects and formats.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");
const json = (p) => JSON.parse(read(p));
const sha256 = (p) => createHash("sha256").update(read(p)).digest("hex");

const BASELINE_JSON = "evidence/M7/baseline.json";
const REPORT = "evidence/M7/report.md";

// ---- runtime -------------------------------------------------------------------------------------------------
const RUNS = [
  { label: "first run", file: "benchmarks/results/runtime/summary.json", report: "benchmarks/results/runtime/report.md" },
  { label: "after K-04, disturbed machine", file: "benchmarks/results/runtime/summary-after-k04.json", report: "benchmarks/results/runtime/report-after-k04.md" },
  { label: "after K-04, quiet machine", file: "benchmarks/results/runtime/summary-after-quiet.json", report: "benchmarks/results/runtime/report-after-quiet.md" },
];

function runRecord(reportPath) {
  const rows = {};
  for (const line of read(reportPath).split("\n")) {
    const m = /^\| ([^|]+?) \| (.+) \|$/.exec(line);
    if (m) rows[m[1].trim()] = m[2].trim();
  }
  return rows;
}

function runtime() {
  const frozen = json("benchmarks/runtime/FROZEN.json");
  const last = frozen.entries[frozen.entries.length - 1];
  const runs = RUNS.map((r) => {
    const s = json(r.file);
    const rec = runRecord(r.report);
    return {
      label: r.label,
      runId: s.runId,
      summary: r.file,
      report: r.report,
      machineLoad: rec["Machine load"] ?? null,
      workloads: s.verdicts.map((v) => ({
        workload: v.workload,
        metric: v.metricName,
        mtek: v.mtek,
        direct: v.direct,
        three: v.three,
        mtekOverDirectPercent: v.mtekOverDirectPercent,
        threeOverDirectPercent: v.threeOverDirectPercent,
        outcome: v.outcome,
      })),
    };
  });
  const quiet = runRecord(RUNS[2].report);
  return {
    frozenTreeHash: last.treeHash,
    thresholdPercent: 20,
    unit: "ms (startup and cycle rows: ms per the metric named)",
    environment: {
      operatingSystem: quiet["Operating system"] ?? null,
      browser: quiet["Browser"] ?? null,
      adapter: quiet["Adapter"] ?? null,
      isFallbackAdapter: quiet["`isFallbackAdapter`"] ?? null,
      toolchain: quiet["Toolchain"] ?? null,
      frames: quiet["Frames"] ?? null,
    },
    runs,
  };
}

// ---- tests of the gate run -------------------------------------------------------------------------------------
function tests() {
  const text = read("evidence/M7/gate/suite-summary.txt");
  const cargo = [...text.matchAll(/^cargo test --workspace --locked \(([^)]*)\): (\{.*\})$/gm)].map((m) => ({ mode: m[1], ...JSON.parse(m[2]) }));
  const unitTests = [...text.matchAll(/^Tests\s+(\d+) passed(?: \| (\d+) skipped)?/gm)];
  const browser = /Mtek browser tests: (\d+) passed \/ (\d+) failed \/ (\d+) not-run \/ (\d+) skipped/.exec(text);
  const vscode = /(\d+) passed, (\d+) failed, of (\d+)/.exec(text);
  const conformance = /conformance: PASS \((\d+) inputs\)/.exec(text);
  const builds = json("evidence/M7/gate/reproducible-builds-final.json");
  return {
    verifiedCommit: builds.commit,
    from: "evidence/M7/gate/suite-summary.txt and evidence/M7/gate/reproducible-builds-final.json (a clean clone of the commit)",
    cargo,
    unit: { workspaces: unitTests.length, passed: unitTests.reduce((s, m) => s + Number(m[1]), 0), skipped: unitTests.reduce((s, m) => s + Number(m[2] ?? 0), 0) },
    browser: browser && { passed: Number(browser[1]), failed: Number(browser[2]), notRun: Number(browser[3]), skipped: Number(browser[4]) },
    vscodeIntegration: vscode && { passed: Number(vscode[1]), failed: Number(vscode[2]), of: Number(vscode[3]) },
    grammarConformanceInputs: conformance && Number(conformance[1]),
    coverage: /(\d+) features, (\d+) positive fixture programs, (\d+) diagnostic codes \((\d+) without a negative test\)/.exec(text)?.slice(1).map(Number),
    reproducibleBuilds: { result: builds.result, scope: "two clean clones of one commit, one machine, one operating system" },
  };
}

// ---- AI ---------------------------------------------------------------------------------------------------------------
const verdict = (v) => (v ? { verdict: v.verdict, reason: v.reason, tokenRatio: v.tokenRatio, completionDifferencePoints: v.completionDifferencePoints, provisional: v.provisional } : null);

function ai() {
  const b = json("evidence/M7/ai-baseline.json");
  const pick = (c) => ({
    label: c.label,
    attempts: c.attempts,
    completed: c.completed,
    completionRate: c.completionRate,
    tokensPerCompletedTask: c.tokensPerCompletedTask,
    costUsd: c.costUsd,
    notJudged: c.notJudged,
  });
  return {
    file: "evidence/M7/ai-baseline.json",
    sha256: sha256("evidence/M7/ai-baseline.json"),
    model: b.measurement.model,
    temperature: b.measurement.temperature,
    trialsPerTask: b.measurement.trialsPerTask,
    main: {
      baseline: pick(b.main.baseline),
      conditions: b.main.conditions.map((c) => ({
        label: c.label ?? c.after?.label,
        before: pick(c.before),
        after: pick(c.after),
        verdictAfter: verdict(c.verdictAgainstBaseline),
      })),
    },
    holdout: b.holdout.conditions.map((c) => ({ set: c.set, ...pick(c), verdict: c.verdictAgainstEarlierBaseline?.verdict ?? null })),
    targets: b.targets,
    holdoutTreeHash: read("benchmarks/holdout.sha256").trim().split(/\s+/)[0],
  };
}

