// ---- the report tables -----------------------------------------------------------------------------------------
const pct = (x) => `${(100 * x).toFixed(1)} %`;
const ms = (x) => `${+x.toFixed(3)} ms`;
const num = (x) => (x === null || x === undefined ? "n/a" : Math.round(x).toLocaleString("en-US"));
const row = (cells) => `| ${cells.join(" | ")} |`;

function tables(b) {
  const out = {};
  const rt = b.runtime.runs;
  const names = rt[0].workloads.map((w) => w.workload);
  out.runtime = [
    row(["Workload", "Metric", "First run Mtek", "Quiet run Mtek", "Quiet run direct WebGPU", "Quiet run three.js", "Quiet run Mtek over direct", "Threshold (20 %)"]),
    row(["---", "---", "---", "---", "---", "---", "---", "---"]),
    ...names.map((n, i) => {
      const a = rt[0].workloads[i];
      const q = rt[2].workloads[i];
      return row([n, a.metric.replace(/ \(.*\)$/, ""), ms(a.mtek), ms(q.mtek), ms(q.direct), ms(q.three), `+${q.mtekOverDirectPercent.toFixed(1)} %`, q.outcome === "exceeds" ? "exceeds" : "within"]);
    }),
  ].join("\n");
  const m = b.ai.main;
  out.aiMain = [
    row(["Condition", "Attempts", "Completed", "Completion", "Tokens per completed task", "Cost (USD)"]),
    row(["---", "---", "---", "---", "---", "---"]),
    row(["three.js baseline (M7-05, not re-run)", m.baseline.attempts, m.baseline.completed, pct(m.baseline.completionRate), num(m.baseline.tokensPerCompletedTask), m.baseline.costUsd.toFixed(2)]),
    ...m.conditions.flatMap((c) => [
      row([`${c.label}, before M7.1`, c.before.attempts, c.before.completed, pct(c.before.completionRate), num(c.before.tokensPerCompletedTask), c.before.costUsd.toFixed(2)]),
      row([`${c.label}, after M7.1`, c.after.attempts, c.after.completed, pct(c.after.completionRate), num(c.after.tokensPerCompletedTask), c.after.costUsd.toFixed(2)]),
    ]),
  ].join("\n");
  out.aiHoldout = [
    row(["Condition", "Set", "Attempts", "Completed", "Completion", "Tokens per completed task", "Verdict against the earlier baseline"]),
    row(["---", "---", "---", "---", "---", "---", "---"]),
    ...b.ai.holdout.map((c) => row([c.label, c.set, c.attempts, c.completed, pct(c.completionRate), num(c.tokensPerCompletedTask), c.verdict ?? "reference"])),
  ].join("\n");
  const t = b.tests;
  out.tests = [
    row(["Stage", "Result"]),
    row(["---", "---"]),
    ...t.cargo.map((c) => row([`cargo test --workspace --locked (${c.mode})`, `${c.passed} passed, ${c.failed} failed, ${c.ignored} ignored`])),
    row(["grammar conformance (pinned llama.cpp backend)", `${t.grammarConformanceInputs} inputs pass`]),
    row(["npm run test:unit", `${t.unit.passed} passed, ${t.unit.skipped} skipped, ${t.unit.workspaces} workspaces`]),
    row(["browser, all projects (MTEK_REQUIRE_GPU=1)", `${t.browser.passed} passed, ${t.browser.failed} failed, ${t.browser.notRun} not run, ${t.browser.skipped} skipped by design`]),
    row(["VS Code integration", `${t.vscodeIntegration.passed} of ${t.vscodeIntegration.of} passed`]),
    row(["coverage matrix", `${t.coverage[0]} features, ${t.coverage[1]} positive programs, ${t.coverage[2]} diagnostic codes, ${t.coverage[3]} without a negative test`]),
  ].join("\n");
  return out;
}

function fill(text, tablesByName) {
  let out = text;
  for (const [name, body] of Object.entries(tablesByName)) {
    const re = new RegExp(`(<!-- baseline:${name}:begin -->\\n)[\\s\\S]*?(<!-- baseline:${name}:end -->)`);
    if (!re.test(out)) throw new Error(`${REPORT}: marker baseline:${name} missing`);
    out = out.replace(re, (_, a, c) => `${a}${body}
${c}`);
  }
  return out;
}

const baseline = build();
const text = JSON.stringify(baseline, null, 2) + "\n";
const report = fill(read(REPORT), tables(baseline));

if (process.argv.includes("--check")) {
  const problems = [];
  if (read(BASELINE_JSON) !== text) problems.push(`${BASELINE_JSON} is not what this script prints`);
  if (read(REPORT) !== report) problems.push(`${REPORT}: a generated table differs from the data`);
  if (problems.length) {
    console.error(problems.map((p) => `gen-m7-baseline: ${p}`).join("\n"));
    process.exit(1);
  }
  console.log("gen-m7-baseline: baseline.json and the report tables follow from the stored results");
} else {
  writeFileSync(join(root, BASELINE_JSON), text);
  writeFileSync(join(root, REPORT), report);
  console.log(`gen-m7-baseline: wrote ${BASELINE_JSON} and the tables of ${REPORT}`);
}
