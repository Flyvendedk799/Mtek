// Generates the manifest validator of @mtek/runtime-web from spec/manifest.schema.json.
//
// Ajv (a devDependency) compiles the schema at build time into a standalone ES module; the module is
// bundled into the runtime, so Ajv itself never ships and never runs in the browser (decision 0007).
// The output is deterministic (no timestamps, no absolute paths) and is not checked in:
//   packages/runtime-web/src/abi/generated/validate-manifest.js
//   packages/runtime-web/src/abi/generated/validate-manifest.d.ts
// It is run by `build`, `check:ts`, `lint` and `test:unit`.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Ajv 8 is a devDependency of the runtime package (npm nests it there because ESLint needs Ajv 6 at the
// root), so it is resolved from that package rather than from this script's location.
const requireFromRuntime = createRequire(resolve(root, "packages/runtime-web/package.json"));
const Ajv2020 = requireFromRuntime("ajv/dist/2020").default;
const standaloneCode = requireFromRuntime("ajv/dist/standalone").default;
const schemaPath = resolve(root, "spec/manifest.schema.json");
const outDir = resolve(root, "packages/runtime-web/src/abi/generated");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

// Ajv 8.20 prints a deprecation notice for the `unicode` option. The option is still honoured and is
// required by the task (it keeps `minLength`/`maxLength` free of the Ajv runtime helper), so only that one
// notice is filtered out; every other warning is still shown.
const logger = {
  log: (...args) => console.log(...args),
  warn: (...args) => {
    if (typeof args[0] === "string" && args[0].startsWith("DEPRECATED: option unicode")) return;
    console.warn(...args);
  },
  error: (...args) => console.error(...args),
};

const ajv = new Ajv2020({
  logger,
  allErrors: true,
  strict: true,
  allowUnionTypes: true, // `type: ["string", "null"]` for nullable fields
  discriminator: true, // tagged unions (`kind` / `class`) give one precise error instead of one per branch
  unicode: false, // length and pattern checks on UTF-16 code units: no import of ajv/dist/runtime/ucs2length
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);
const generated = standaloneCode(ajv, validate);

// The bundled runtime must not need Ajv at run time: fail the build if the generated code imports anything.
const importLike = /\b(?:import\s*[\w{*"']|import\s*\(|require\s*\()/;
const offending = generated.split("\n").filter((line) => importLike.test(line) && /ajv/.test(line));
if (offending.length > 0 || /from\s+["']ajv/.test(generated) || /require\(["']ajv/.test(generated)) {
  console.error("gen-manifest-validator: generated validator imports Ajv at run time:");
  for (const line of offending) console.error("  " + line.trim());
  console.error("Remove the schema keyword that needs an Ajv runtime helper (uniqueItems on objects, const/enum with objects, format, ...).");
  process.exit(1);
}

const header =
  "// Generated by scripts/gen-manifest-validator.mjs from spec/manifest.schema.json. Do not edit.\n";

const declarations = `${header}// Standalone Ajv (2020-12) validator for program.manifest.json. Returns true when the value is valid;
// the failures of the last call are in \`validate.errors\` (reset by every call).

export interface ManifestValidationError {
  readonly instancePath: string;
  readonly schemaPath: string;
  readonly keyword: string;
  readonly params: Readonly<Record<string, unknown>>;
  readonly message?: string;
  /** Set by the \`propertyNames\` keyword: the offending property name. */
  readonly propertyName?: string;
}

export interface ManifestValidateFunction {
  (data: unknown): boolean;
  errors?: readonly ManifestValidationError[] | null;
}

export declare const validate: ManifestValidateFunction;
export default validate;
`;

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return false;
  writeFileSync(path, content);
  return true;
}

mkdirSync(outDir, { recursive: true });
const changedJs = writeIfChanged(resolve(outDir, "validate-manifest.js"), header + generated);
const changedDts = writeIfChanged(resolve(outDir, "validate-manifest.d.ts"), declarations);
if (changedJs || changedDts) {
  console.log("gen-manifest-validator: wrote packages/runtime-web/src/abi/generated/validate-manifest.{js,d.ts}");
}
