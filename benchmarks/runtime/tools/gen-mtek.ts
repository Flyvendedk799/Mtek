// Writes the Mtek program of each workload from its `workload.json` and `common/layout.ts`, so that the three
// implementations cannot drift apart: the positions, angles, scales, phases and colours of the program are the ones the
// direct-WebGPU and three.js implementations compute at run time.
//
//   node tools/gen-mtek.ts            writes <workload>/mtek/{mtek.toml,src/main.mtek}
//   node tools/gen-mtek.ts --check    fails when a committed program differs from what this generator prints
//
// `mtekProject(workload, variant)` is also used by `prepare.ts` to derive the edited program of the reload step of
// mount-reload-dispose (`variant: "edited"`), which is never committed.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import protocol from "../protocol.json" with { type: "json" };
import { RUNTIME_ROOT, WORKLOADS, type WorkloadName } from "./paths.ts";
import {
  assetHeavy,
  changingMaterials,
  changingTransforms,
  constantScene,
  cycleScene,
  f32Literal,
  physicsBodies,
  repeatedMeshes,
  type AssetHeavyDefinition,
  type ChangingMaterialsDefinition,
  type ChangingTransformsDefinition,
  type ConstantSceneDefinition,
  type CyclesDefinition,
  type PhysicsBodiesDefinition,
  type RepeatedMeshesDefinition,
  type Vec3,
} from "../common/layout.ts";


export interface WorkloadFile {
  readonly name: string;
  readonly title: string;
  readonly kind: "frames" | "startup" | "cycles";
  readonly description: string;
  readonly camera: { readonly position: Vec3; readonly target: Vec3 };
  readonly parityFrames: number;
  readonly definition: Record<string, unknown>;
}

export function readWorkload(name: WorkloadName): WorkloadFile {
  return JSON.parse(readFileSync(join(RUNTIME_ROOT, name, "workload.json"), "utf8")) as WorkloadFile;
}

const f = f32Literal;
const vec3 = (v: Vec3): string => `vec3(${f(v[0])}, ${f(v[1])}, ${f(v[2])})`;
const pad = (index: number, width: number): string => String(index).padStart(width, "0");

const TOML = (title: string): string => `[project]
name = "runtime-bench"
language = "0.1"
entry = "src/main.mtek"
scene = "Bench"

[build]
target = "web"
title = "${title}"
`;

function header(workload: string): string {
  return `// Generated by benchmarks/runtime/tools/gen-mtek.ts from ${workload}/workload.json and common/layout.ts. Do not edit:
// change the definition and regenerate (\`node tools/gen-mtek.ts\`), or the frozen-definition check fails.
`;
}

function sceneHead(workload: WorkloadFile): string {
  const { position, target } = workload.camera;
  const camera = protocol.camera;
  return `    clear_color: ${protocol.clearColorSrgb};
    camera Main {
        position: ${vec3(position)};
        target: ${vec3(target)};
        projection: Perspective { fov_y: ${f(camera.fovY)}; near: ${f(camera.near)}; far: ${f(camera.far)} };
    }
`;
}

function constantProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as ConstantSceneDefinition;
  const boxes = constantScene(def);
  const width = String(boxes.length - 1).length;
  const size = f(workload.definition["boxSize"] as number);
  return `${header(workload.name)}
// A block of one mesh; the colour is a construction-time param, so blocks of one colour share their parameter block.
prefab Block {
    param at: vec3;
    param yaw: f32;
    param tint: color;
    position: at;
    rotation: quat.axis_angle(vec3(0.0, 1.0, 0.0), yaw);
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: tint };
}

scene Bench {
${sceneHead(workload)}
${boxes
  .map(
    (b) =>
      `    entity B${pad(b.index, width)}: Block { at: ${vec3(b.position)}; yaw: ${f(b.yaw)}; tint: ${def.palette[b.colorIndex] ?? "#ffffff"}; }`,
  )
  .join("\n")}
}
`;
}

function transformsProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as ChangingTransformsDefinition;
  const boxes = changingTransforms(def);
  const width = String(boxes.length - 1).length;
  const size = f(def.boxSize);
  return `${header(workload.name)}
// Position and rotation are bound to the frame time: they are re-evaluated every frame.
prefab Mover {
    param at: vec3;
    param phase: f32;
    position: bind(vec3(at.x, at.y + ${f(def.amplitude)} * sin(frame.time * ${f(def.frequency)} + phase), at.z));
    rotation: bind(quat.axis_angle(vec3(0.0, 1.0, 0.0), frame.time * ${f(def.spin)} + phase));
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: ${def.color} };
}

scene Bench {
${sceneHead(workload)}
${boxes.map((b) => `    entity M${pad(b.index, width)}: Mover { at: ${vec3(b.position)}; phase: ${f(b.phase)}; }`).join("\n")}
}
`;
}

function materialsProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as ChangingMaterialsDefinition;
  const boxes = changingMaterials(def);
  const width = String(boxes.length - 1).length;
  const size = f(def.boxSize);
  const channel = (offset: number): string =>
    `0.5 + 0.5 * sin(frame.time * ${f(def.colorFrequency)} + phase${offset === 0 ? "" : ` + ${f(offset)}`})`;
  return `${header(workload.name)}
// The colour param of the material is bound to the frame time: every box owns a parameter block that changes every frame.
prefab Glow {
    param at: vec3;
    param phase: f32;
    position: at;
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: bind(color.linear(vec3(${def.colorOffsets.map(channel).join(", ")}), 1.0)) };
}

scene Bench {
${sceneHead(workload)}
${boxes.map((b) => `    entity G${pad(b.index, width)}: Glow { at: ${vec3(b.position)}; phase: ${f(b.phase)}; }`).join("\n")}
}
`;
}

function repeatedProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as RepeatedMeshesDefinition;
  const boxes = repeatedMeshes(def);
  const width = String(boxes.length - 1).length;
  const size = f(def.boxSize);
  return `${header(workload.name)}
// 2,000 entities of one mesh and one (constant) parameter block: the runtime draws them with one instanced draw.
prefab Block {
    param at: vec3;
    param yaw: f32;
    param s: f32;
    position: at;
    rotation: quat.axis_angle(vec3(0.0, 1.0, 0.0), yaw);
    scale: vec3(s, s, s);
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: ${def.color} };
}

scene Bench {
${sceneHead(workload)}
${boxes.map((b) => `    entity R${pad(b.index, width)}: Block { at: ${vec3(b.position)}; yaw: ${f(b.yaw)}; s: ${f(b.scale)}; }`).join("\n")}
}
`;
}

function physicsProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as PhysicsBodiesDefinition;
  const boxes = physicsBodies(def);
  const width = String(boxes.length - 1).length;
  const size = f(def.boxSize);
  const [fx, fz] = def.forceFrequency;
  const floor = def.floorSize;
  return `${header(workload.name)}
// A dynamic box. Every fixed tick a small horizontal force pushes it, so the solver never lets it sleep.
prefab Crate {
    param at: vec3;
    param phase: f32;
    param tint: color;
    position: at;
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: tint };
    body: Dynamic { mass: ${f(def.mass)} };
    collider: BoxCollider { size: vec3(${size}, ${size}, ${size}); friction: ${f(def.friction)} };

    fixed_update(dt: f32) {
        self.body.apply_force(vec3(
            ${f(def.forceAmplitude)} * sin(frame.time * ${f(fx)} + phase),
            0.0,
            ${f(def.forceAmplitude)} * cos(frame.time * ${f(fz)} + 2.0 * phase)));
    }
}

scene Bench {
${sceneHead(workload)}
    entity Floor {
        position: vec3(0.0, ${f(-floor[1] / 2)}, 0.0);
        mesh: Box { size: ${vec3(floor)} };
        material: Unlit { color: #2a3342 };
        body: Static {};
        collider: BoxCollider { size: ${vec3(floor)}; friction: ${f(def.friction)} };
    }
${boxes
  .map(
    (b) =>
      `    entity C${pad(b.index, width)}: Crate { at: ${vec3(b.position)}; phase: ${f(b.phase)}; tint: ${def.layerColors[b.colorIndex] ?? "#ffffff"}; }`,
  )
  .join("\n")}
}
`;
}

function assetProgram(workload: WorkloadFile): string {
  const def = workload.definition as unknown as AssetHeavyDefinition;
  const placed = assetHeavy(def);
  const width = String(placed.length - 1).length;
  const textures = Array.from({ length: def.textures }, (_, i) => `const T${i} = asset.texture("textures/t${i}.png");`).join("\n");
  return `${header(workload.name)}
const ROCKS = asset.glb("models/rocks.glb");
${textures}

// Unlit, textured: the texel of the bound image at the interpolated uv.
material Skin {
    param tex: texture;
    param smp: sampler = sampler.linear_repeat();
    fragment(surface: SurfaceInput) -> color {
        let texel = sample(tex, smp, surface.uv);
        return color.linear(texel.xyz, 1.0);
    }
}

scene Bench {
${sceneHead(workload)}
${placed
  .map(
    (p) =>
      `    entity S${pad(p.index, width)} { position: ${vec3(p.position)}; mesh: ROCKS.mesh("Rock${p.meshIndex}"); material: Skin { tex: T${p.textureIndex} }; }`,
  )
  .join("\n")}
}
`;
}

function cyclesProgram(workload: WorkloadFile, variant: "primary" | "edited"): string {
  const def = workload.definition as unknown as CyclesDefinition;
  const boxes = cycleScene(def, variant === "edited" ? def.reloadPaletteShift : 0);
  const width = String(boxes.length - 1).length;
  const size = f(def.boxSize);
  return `${header(workload.name)}${variant === "edited" ? "// The edited program of the reload step: the same scene with the palette shifted by one entry.\n" : ""}
prefab Block {
    param at: vec3;
    param yaw: f32;
    param tint: color;
    position: at;
    rotation: quat.axis_angle(vec3(0.0, 1.0, 0.0), yaw);
    mesh: Box { size: vec3(${size}, ${size}, ${size}) };
    material: Unlit { color: tint };
}

scene Bench {
${sceneHead(workload)}
${boxes
  .map(
    (b) =>
      `    entity B${pad(b.index, width)}: Block { at: ${vec3(b.position)}; yaw: ${f(b.yaw)}; tint: ${def.palette[b.colorIndex] ?? "#ffffff"}; }`,
  )
  .join("\n")}
}
`;
}

/** The files of the Mtek project of `name`, keyed by their path inside the project directory. */
export function mtekProject(name: WorkloadName, variant: "primary" | "edited" = "primary"): Map<string, string> {
  const workload = readWorkload(name);
  let source: string;
  switch (name) {
    case "constant-scene":
      source = constantProgram(workload);
      break;
    case "changing-transforms":
      source = transformsProgram(workload);
      break;
    case "changing-material-params":
      source = materialsProgram(workload);
      break;
    case "repeated-meshes":
      source = repeatedProgram(workload);
      break;
    case "asset-heavy-startup":
      source = assetProgram(workload);
      break;
    case "physics-bodies":
      source = physicsProgram(workload);
      break;
    case "mount-reload-dispose":
      source = cyclesProgram(workload, variant);
      break;
  }
  if (variant === "edited" && name !== "mount-reload-dispose") throw new Error(`only mount-reload-dispose has an edited program, not ${name}`);
  return new Map([
    ["mtek.toml", TOML(workload.title)],
    ["src/main.mtek", source],
  ]);
}

function main(): void {
  const check = process.argv.includes("--check");
  let failed = false;
  for (const name of WORKLOADS) {
    for (const [path, text] of mtekProject(name)) {
      const target = join(RUNTIME_ROOT, name, "mtek", path);
      if (check) {
        const current = existsSync(target) ? readFileSync(target, "utf8") : null;
        if (current !== text) {
          failed = true;
          process.stderr.write(`${name}/mtek/${path} is not what tools/gen-mtek.ts prints\n`);
        }
      } else {
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, text);
      }
    }
  }
  if (failed) process.exitCode = 1;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(import.meta.filename)) main();
